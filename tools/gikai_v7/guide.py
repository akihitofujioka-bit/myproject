def button_tip(text: str) -> str:
    """ボタンの字から説明を探す。手順のボタン（例「9. 一般質問」）はその手順の説明。"""
    if text in BUTTON_TIPS:
        return BUTTON_TIPS[text]
    number, _, name = text.partition(". ")
    if number.isdigit() and name in GUIDE:
        return GUIDE[name][0].replace("このページは何か：", "")
    return ""
